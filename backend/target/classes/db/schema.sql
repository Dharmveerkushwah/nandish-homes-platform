-- Nandish Homes Oracle schema. Run once with a deployment user, then keep
-- spring.jpa.hibernate.ddl-auto=validate in every environment.
CREATE SEQUENCE NH_USER_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_ROOM_TYPE_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_ROOM_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_BOOKING_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_GUEST_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_ROOM_BLOCK_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_REVIEW_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_GALLERY_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_PLACE_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_CONTENT_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_FAQ_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_OFFER_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_CONTACT_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE NH_PAYMENT_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE NH_ROLES (ROLE_ID NUMBER(19) PRIMARY KEY, ROLE_NAME VARCHAR2(40) UNIQUE NOT NULL);
CREATE TABLE NH_USERS (
  USER_ID NUMBER(19) PRIMARY KEY, EMAIL VARCHAR2(180) UNIQUE NOT NULL,
  PASSWORD_HASH VARCHAR2(255) NOT NULL, DISPLAY_NAME VARCHAR2(120) NOT NULL,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE NH_USER_ROLES (
  USER_ID NUMBER(19) NOT NULL, ROLE_NAME VARCHAR2(40) NOT NULL,
  CONSTRAINT PK_NH_USER_ROLES PRIMARY KEY (USER_ID, ROLE_NAME),
  CONSTRAINT FK_NH_UR_USER FOREIGN KEY (USER_ID) REFERENCES NH_USERS(USER_ID)
);
CREATE TABLE NH_ROOM_TYPES (
  ROOM_TYPE_ID NUMBER(19) PRIMARY KEY, NAME VARCHAR2(120) NOT NULL,
  SLUG VARCHAR2(140) UNIQUE NOT NULL, DESCRIPTION VARCHAR2(2000),
  BASE_PRICE NUMBER(12,2) NOT NULL, MAX_GUESTS NUMBER(3) NOT NULL,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE NH_ROOMS (
  ROOM_ID NUMBER(19) PRIMARY KEY, ROOM_CODE VARCHAR2(40) UNIQUE NOT NULL,
  DISPLAY_NAME VARCHAR2(160) NOT NULL, ROOM_TYPE_ID NUMBER(19) NOT NULL,
  STATUS VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL, FLOOR_LABEL VARCHAR2(60),
  IS_FEATURED NUMBER(1) DEFAULT 0 NOT NULL, IMAGE_URL VARCHAR2(500),
  SIZE_SQFT NUMBER(8), PRICE_OVERRIDE NUMBER(12,2),
  CONSTRAINT FK_NH_ROOM_TYPE FOREIGN KEY (ROOM_TYPE_ID) REFERENCES NH_ROOM_TYPES(ROOM_TYPE_ID)
);
CREATE TABLE NH_ROOM_AMENITIES (ROOM_ID NUMBER(19) NOT NULL, AMENITY_NAME VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_NH_ROOM_AMENITIES PRIMARY KEY (ROOM_ID, AMENITY_NAME),
  CONSTRAINT FK_NH_RA_ROOM FOREIGN KEY (ROOM_ID) REFERENCES NH_ROOMS(ROOM_ID));
CREATE TABLE NH_ROOM_IMAGES (IMAGE_ID NUMBER(19) PRIMARY KEY, ROOM_ID NUMBER(19) NOT NULL,
  IMAGE_URL VARCHAR2(500) NOT NULL, ALT_TEXT VARCHAR2(200), SORT_ORDER NUMBER(5) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_NH_RI_ROOM FOREIGN KEY (ROOM_ID) REFERENCES NH_ROOMS(ROOM_ID));
CREATE TABLE NH_GUESTS (GUEST_ID NUMBER(19) PRIMARY KEY, FULL_NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(180) NOT NULL, PHONE VARCHAR2(30) NOT NULL, SPECIAL_REQUEST VARCHAR2(500));
CREATE TABLE NH_BOOKINGS (
  BOOKING_ID NUMBER(19) PRIMARY KEY, BOOKING_REFERENCE VARCHAR2(24) UNIQUE NOT NULL,
  ROOM_ID NUMBER(19) NOT NULL, CHECK_IN DATE NOT NULL, CHECK_OUT DATE NOT NULL,
  GUEST_COUNT NUMBER(3) NOT NULL, STATUS VARCHAR2(30) NOT NULL,
  TOTAL_AMOUNT NUMBER(12,2) NOT NULL, CURRENCY_CODE CHAR(3) DEFAULT 'INR' NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_NH_BOOKING_ROOM FOREIGN KEY (ROOM_ID) REFERENCES NH_ROOMS(ROOM_ID),
  CONSTRAINT CK_NH_BOOKING_DATES CHECK (CHECK_OUT > CHECK_IN)
);
CREATE TABLE NH_BOOKING_GUESTS (BOOKING_ID NUMBER(19) NOT NULL, GUEST_ID NUMBER(19) NOT NULL,
  CONSTRAINT PK_NH_BOOKING_GUESTS PRIMARY KEY (BOOKING_ID, GUEST_ID),
  CONSTRAINT FK_NH_BG_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES NH_BOOKINGS(BOOKING_ID),
  CONSTRAINT FK_NH_BG_GUEST FOREIGN KEY (GUEST_ID) REFERENCES NH_GUESTS(GUEST_ID));
CREATE TABLE NH_ROOM_BLOCKS (BLOCK_ID NUMBER(19) PRIMARY KEY, ROOM_ID NUMBER(19) NOT NULL,
  START_DATE DATE NOT NULL, END_DATE DATE NOT NULL, REASON VARCHAR2(300) NOT NULL,
  CONSTRAINT FK_NH_BLOCK_ROOM FOREIGN KEY (ROOM_ID) REFERENCES NH_ROOMS(ROOM_ID));
CREATE TABLE NH_PAYMENTS (PAYMENT_ID NUMBER(19) PRIMARY KEY, BOOKING_ID NUMBER(19) NOT NULL,
  PROVIDER VARCHAR2(30) NOT NULL, PROVIDER_REFERENCE VARCHAR2(160), AMOUNT NUMBER(12,2) NOT NULL,
  STATUS VARCHAR2(30) NOT NULL, PAID_AT TIMESTAMP WITH TIME ZONE,
  CONSTRAINT FK_NH_PAYMENT_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES NH_BOOKINGS(BOOKING_ID));
CREATE TABLE NH_OFFERS (OFFER_ID NUMBER(19) PRIMARY KEY, CODE VARCHAR2(50) UNIQUE NOT NULL,
  NAME VARCHAR2(120) NOT NULL, DISCOUNT_PERCENT NUMBER(5,2), ACTIVE_FROM DATE, ACTIVE_TO DATE,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE NH_BOOKING_OFFERS (BOOKING_ID NUMBER(19) NOT NULL, OFFER_ID NUMBER(19) NOT NULL,
  CONSTRAINT PK_NH_BOOKING_OFFERS PRIMARY KEY (BOOKING_ID, OFFER_ID));
CREATE TABLE NH_REVIEWS (REVIEW_ID NUMBER(19) PRIMARY KEY, GUEST_NAME VARCHAR2(120) NOT NULL,
  RATING NUMBER(1) NOT NULL, REVIEW_TEXT VARCHAR2(2000) NOT NULL, IS_PUBLISHED NUMBER(1) DEFAULT 0 NOT NULL);
CREATE TABLE NH_GALLERY (GALLERY_ID NUMBER(19) PRIMARY KEY, TITLE VARCHAR2(160) NOT NULL,
  IMAGE_URL VARCHAR2(500) NOT NULL, CATEGORY VARCHAR2(60), SORT_ORDER NUMBER(5) DEFAULT 0 NOT NULL);
CREATE TABLE NH_PLACES (PLACE_ID NUMBER(19) PRIMARY KEY, NAME VARCHAR2(160) NOT NULL,
  DESCRIPTION VARCHAR2(1000), IMAGE_URL VARCHAR2(500), DISTANCE_LABEL VARCHAR2(80));
CREATE TABLE NH_CONTENT (CONTENT_ID NUMBER(19) PRIMARY KEY, CONTENT_KEY VARCHAR2(100) UNIQUE NOT NULL,
  TITLE VARCHAR2(200), BODY CLOB, UPDATED_AT TIMESTAMP WITH TIME ZONE);
CREATE TABLE NH_FAQ (FAQ_ID NUMBER(19) PRIMARY KEY, QUESTION VARCHAR2(500) NOT NULL,
  ANSWER VARCHAR2(2000) NOT NULL, SORT_ORDER NUMBER(5) DEFAULT 0 NOT NULL, IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE NH_CONTACT_MESSAGES (MESSAGE_ID NUMBER(19) PRIMARY KEY, NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(180) NOT NULL, PHONE VARCHAR2(30), MESSAGE_TEXT VARCHAR2(2000) NOT NULL,
  STATUS VARCHAR2(30) DEFAULT 'NEW' NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL);
CREATE TABLE NH_NOTIFICATIONS (NOTIFICATION_ID NUMBER(19) PRIMARY KEY, USER_ID NUMBER(19),
  TITLE VARCHAR2(200) NOT NULL, BODY VARCHAR2(1000) NOT NULL, IS_READ NUMBER(1) DEFAULT 0 NOT NULL);
CREATE TABLE NH_EMAIL_LOGS (EMAIL_LOG_ID NUMBER(19) PRIMARY KEY, RECIPIENT VARCHAR2(180) NOT NULL,
  SUBJECT VARCHAR2(300) NOT NULL, STATUS VARCHAR2(30) NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL);
CREATE TABLE NH_WHATSAPP_LOGS (WHATSAPP_LOG_ID NUMBER(19) PRIMARY KEY, PHONE VARCHAR2(30) NOT NULL,
  MESSAGE_TEXT VARCHAR2(1000) NOT NULL, STATUS VARCHAR2(30) NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL);
CREATE TABLE NH_AUDIT_LOGS (AUDIT_ID NUMBER(19) PRIMARY KEY, USER_ID NUMBER(19), ACTION_NAME VARCHAR2(120) NOT NULL,
  ENTITY_NAME VARCHAR2(120), ENTITY_ID NUMBER(19), DETAILS CLOB, CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL);